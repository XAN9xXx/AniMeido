"""Extract the approved loading tracks without creating a runtime animator per sample."""
import argparse
import subprocess
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
X = "{http://schemas.microsoft.com/winfx/2006/xaml}"
CURVES = {
    "0.13,0.21,0.1,0.7": 2,
    "0.02,0.33,0.38,0.77": 3,
    "0.57,0.17,0.95,0.75": 4,
    "0,0.19,0.07,0.72": 5,
    "0,0,0.95,0.37": 6,
    "0.4,0,0.2,1": 7,
}


def seconds(value):
    parts = [float(p) for p in value.split(":")]
    return sum(p * (60 ** i) for i, p in enumerate(reversed(parts)))


def number(value):
    return format(float(value), ".9g")


def load(revision, name, template):
    path = "AniMeido.Desktop/Themes/" + name
    source = subprocess.check_output(["git", "show", f"{revision}:{path}"], cwd=ROOT)
    document = ET.fromstring(source)
    return next(e for e in document if e.get(X + "Key") == template)


def track(template, name, prop, initial=0):
    animation = next((e for e in template.iter() if e.tag.endswith("DoubleAnimationUsingKeyFrames")
                      and e.get("Storyboard.TargetName") == name and e.get("Storyboard.TargetProperty") == prop), None)
    if animation is None:
        return "null"
    values = []
    for frame in animation:
        if frame.get("KeySpline") is not None and frame.get("KeySpline") not in CURVES:
            raise ValueError("Unknown approved easing: " + frame.get("KeySpline"))
        curve = 1 if frame.tag.endswith("DiscreteDoubleKeyFrame") else CURVES.get(frame.get("KeySpline"), 0)
        values.extend((number(seconds(frame.get("KeyTime"))), frame.get("Value"), str(curve)))
    delay = seconds(animation.get("BeginTime", "0"))
    repeat = seconds(animation.get("Duration")) if animation.get("RepeatBehavior") == "Forever" else 0
    return "new([" + ", ".join(values) + f"], {number(delay)}, {number(initial)}f, {number(repeat)})"


def named(template, name):
    return next(e for e in template.iter() if e.get(X + "Name") == name)


def node(center, radius, **tracks):
    args = [f"new({number(center[0])}f, {number(center[1])}f)", f"new({number(radius[0])}f, {number(radius[1])}f)"]
    args.extend(f"{key}: {value}" for key, value in tracks.items() if value != "null")
    return "            new(" + ",\n                ".join(args) + "),"


def candidate(label, size, period, nodes, connected=False):
    return (f"    private static readonly DesktopLoadingMotion {label}Motion = new({size}, {period},\n"
            + "        [\n" + "\n".join(nodes) + "\n        ]" + (", true" if connected else "") + ");\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-revision", default="5cbcd6c")
    args = parser.parse_args()
    rev = args.source_revision
    output = ["// Generated by Tools/Build-DesktopLoadingMotion.py from approved templates at " + rev + ".",
              "// Gemini motion: ushan0v/gemini-editor, MIT, 10380f32a47a9e2b85848974b66b5b7ec9d036db.",
              "namespace AniMeido.App.Services;", "", "internal sealed partial class DesktopLoadingMotion", "{"]
    template = load(rev, "DesktopClassicProgressRing.xaml", "DesktopClassicProgressRingTemplate")
    nodes = [node((16, 2), (2, 2), opacity=track(template, f"Dot{i}", "Opacity"),
                  rotation=track(template, f"Rotation{i}", "Angle", -110 - i * 6)) for i in range(5)]
    output.append(candidate("FiveDots", 32, 4.305, nodes))
    for prefix, duration in [("Orbit", "3.666667"), ("Breath", "0.666667")]:
        template = load(rev, "DesktopClaudeProgressRings.xaml", f"DesktopClaude{prefix}ProgressRingTemplate")
        duration = next(e for e in template.iter() if e.tag.endswith("Storyboard")).get("Duration")
        nodes = []
        for i in range(3):
            name = f"{prefix}Dot{i}Geometry"
            geometry = named(template, name)
            parent = next(e for e in template.iter() if geometry in list(e))
            path = next(e for e in template.iter() if parent in list(e))
            translation = next(e for e in path.iter() if e.tag.endswith("TranslateTransform")).get(X + "Name")
            radius = (geometry.get("RadiusX"), geometry.get("RadiusY"))
            nodes.append(node(geometry.get("Center").split(","), radius,
                              x=track(template, translation, "X"), y=track(template, translation, "Y"),
                              rx=track(template, name, "RadiusX", radius[0]), ry=track(template, name, "RadiusY", radius[1])))
        output.append(candidate(prefix, 48, number(seconds(duration)), nodes))
    template = load(rev, "DesktopClaudeProgressRings.xaml", "DesktopClaudeQuietProgressRingTemplate")
    nodes = [node((9.5 + i * 6.5, 16), (1.5, 1.5),
                  y=track(template, f"QuietDot{i}Translation", "Y", 2), opacity=track(template, f"QuietDot{i}", "Opacity"))
             for i in range(3)]
    output.append(candidate("Quiet", 32, 1.9, nodes))
    template = load(rev, "DesktopGeminiProgressRing.xaml", "DesktopGeminiProgressRingTemplate")
    nodes = [node((2, 2), (2, 2), x=track(template, f"Gemini{side}Offset", "X", x),
                  y=track(template, f"Gemini{side}Offset", "Y", y))
             for side, x, y in [("RIGHT", 18.6, 7), ("CENTER", 12, 9.037), ("LEFT", 5.4, 15.744)]]
    output.append(candidate("Gemini", 28, 11.532509, nodes))
    template = load(rev, "DesktopThemeResources.xaml", "DesktopPaperProgressRingTemplate")
    nodes = []
    for i in range(1, 5):
        geometry = named(template, f"PaperDot{i}Geometry")
        nodes.append(node(geometry.get("Center").split(","), (9, 9),
                          x=track(template, f"PaperDot{i}Translation", "X"), y=track(template, f"PaperDot{i}Translation", "Y"),
                          opacity=track(template, f"PaperDot{i}", "Opacity", 0 if i == 4 else 1)))
    output.append(candidate("Nodes", 120, 8.45, nodes, connected=True))
    output.append("}")
    target = ROOT / "AniMeido.Desktop/Services/DesktopLoadingMotionData.cs"
    target.write_bytes(("\ufeff" + "\r\n".join(output) + "\r\n").encode("utf-8"))
    print(target)


if __name__ == "__main__":
    main()
